#!/usr/bin/env python3
"""Write _index.md in each folder named: one line per note, built from the note itself.

    python -I _tools/index.py FOLDER [FOLDER ...]

FOLDER is relative to the current folder or to the workspace root (the folder that holds _tools/);
a folder that does not exist is skipped. A note is a .md file in the folder, or a subfolder with a
CONTEXT.md (a record). Each line is  - [title](file) - description (status) . The title falls back
to the first heading, then the file name; description and status appear when the frontmatter has
them. Rerun after adding or changing notes; never edit _index.md by hand. Standard library only.
"""
import json
import re
import sys
import urllib.parse
from pathlib import Path

try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

NOT_NOTES = {"_index.md", "index.md", "log.md", "context.md", "agents.md", "claude.md", "gemini.md"}


def split(text):
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            return text[3:end], text[end + 4:]
    return "", text


def field(front, name):
    """One frontmatter value as one line: plain or quoted, a > or | block, or a - list joined by ', '."""
    lines = front.splitlines()
    for i, line in enumerate(lines):
        m = re.match(rf"{name}:(?:[ \t]+(.*))?$", line)
        if m:
            break
    else:
        return ""
    v = (m.group(1) or "").strip()
    below = []
    for line in lines[i + 1:]:
        if line.strip() and not line[:1].isspace():
            break
        below.append(line.strip())
    if v in ("", ">", "|", ">-", "|-", ">+", "|+"):
        items = [x[2:].strip() if x.startswith("- ") else x for x in below if x]
        return (", " if v == "" and below and below[0].startswith("- ") else " ").join(items)
    if v[:1] not in "\"'":
        v = re.split(r"\s+#", v, maxsplit=1)[0]  # drop a YAML comment
    if len(v) > 1 and v[0] == v[-1] == '"':
        try:
            return json.loads(v)  # YAML double quotes allow \u escapes
        except ValueError:
            return v[1:-1]
    return v[1:-1] if len(v) > 1 and v[0] == v[-1] == "'" else v


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    root = Path(__file__).resolve().parent.parent
    for arg in sys.argv[1:]:
        folder = Path(arg) if Path(arg).is_dir() else root / arg
        if not folder.is_dir():
            print(f"skipped {arg}: no such folder")
            continue
        lines = ["<!-- generated by _tools/index.py; do not edit -->", f"# {folder.resolve().name.capitalize()}", ""]
        notes = [f for f in folder.glob("*.md") if f.name.lower() not in NOT_NOTES]
        records = [d / "CONTEXT.md" for d in folder.iterdir() if d.is_dir() and (d / "CONTEXT.md").is_file()]
        for f in sorted(notes + records, key=lambda p: p.relative_to(folder).as_posix()):
            front, body = split(f.read_text(encoding="utf-8-sig", errors="replace"))
            heading = re.search(r"^# (.+)$", body, re.M)
            name = urllib.parse.quote(f.relative_to(folder).as_posix())
            line = f"- [{field(front, 'title') or (heading.group(1).strip() if heading else f.stem)}]({name})"
            if field(front, "description"):
                line += f" - {field(front, 'description')}"
            if field(front, "status"):
                line += f" ({field(front, 'status')})"
            lines.append(line)
        with (folder / "_index.md").open("w", encoding="utf-8", newline="\n") as out:  # Python 3.9 has no write_text(newline=)
            out.write("\n".join(lines) + "\n")
        print(f"wrote {folder.as_posix()}/_index.md: {len(lines) - 3} notes")


if __name__ == "__main__":
    main()
